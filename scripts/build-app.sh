#!/bin/bash
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"
source "$ROOT/scripts/toolchain.sh"
swift build "${SWIFT_OPTIONS[@]}" -c release
BIN_DIR="$(swift build "${SWIFT_OPTIONS[@]}" -c release --show-bin-path)"
APP="$ROOT/dist/MagicWine.app"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"
cp "$BIN_DIR/MagicWine" "$APP/Contents/MacOS/MagicWine"
cp "$ROOT/Resources/Info.plist" "$APP/Contents/Info.plist"
cp "$ROOT/LICENSE" "$APP/Contents/Resources/LICENSE"
cp "$ROOT/LICENSE" "$ROOT/dist/LICENSE"
cp "$BIN_DIR/magicwine-cli" "$ROOT/dist/magicwine"
RESOURCE_BUNDLE="MagicWine_MagicWineCore.bundle"
rm -rf "$APP/Contents/Resources/$RESOURCE_BUNDLE" "$ROOT/dist/$RESOURCE_BUNDLE"
cp -R "$BIN_DIR/$RESOURCE_BUNDLE" "$APP/Contents/Resources/$RESOURCE_BUNDLE"
cp -R "$BIN_DIR/$RESOURCE_BUNDLE" "$ROOT/dist/$RESOURCE_BUNDLE"
/usr/bin/plutil -lint "$APP/Contents/Info.plist"
/usr/bin/codesign --force --sign - "$APP"
printf '\nBuilt %s\nCLI: %s/dist/magicwine\nLaunch: open "%s"\n' "$APP" "$ROOT" "$APP"
